package com.vg.run

/**
 * The paired-contact vault transaction — hoisted to commonMain so BOTH
 * platforms run the IDENTICAL sequence and read [VaultSeedDefaults] instead of
 * hardcoding the trust level / inbox lifetime. iOS previously hardcoded
 * `trustLevel: 0` and `86_400_000 * 365` with a "must equal VaultSeedDefaults"
 * comment — and once shipped `trustLevel = 1`, silently differing from Android.
 *
 * Writes, in order: the ContactRecord (fresh anti-replay counters via defaults),
 * the peer's outbound + control-outbound inbox rows (OPTIONAL — absent from a
 * secret-only scan / pre-v7 peer), our inbound + control-inbound rows, the
 * peer's/our GROUP rows (OPTIONAL, same rule), and the ratchet-capable marker.
 * The [contactId] is generated by the caller (the only platform-specific bit — a
 * random opaque id); everything drift-prone lives here.
 */
object PairingVault {

    /**
     * @Throws so a vault write failure aborts the add cleanly on the caller
     * (fail-closed for anti-replay / capability integrity) rather than leaving a
     * half-written contact.
     */
    @Throws(Throwable::class)
    fun savePairedContact(
        vault: VaultDatabase,
        contactId: String,
        sharedSecret: ByteArray,
        peerInboxId: String?,
        peerWriteCap: String?,
        peerCtlInboxId: String?,
        peerCtlWriteCap: String?,
        myInboxId: String,
        myReadCap: String,
        myCtlInboxId: String,
        myCtlReadCap: String,
        alias: String,
        mnemonic: String = "",
        // The two PAIRING-SECRET HALVES, and whether the
        // peer's code carried `"rv":"2"` ([PairingScan.roleRuleV2]). They are used
        // ONCE, here, to derive and persist a single ordering bit
        // ([MessageManager.recordRatchetRoleInputs]); neither half is stored, and
        // neither array is retained or mutated by this call — the caller keeps
        // ownership and its existing wipe.
        //
        // Nullable + defaulted so the pre-A signature still type-checks for any
        // caller that genuinely has no halves (none ship today; the commonTest
        // fixtures do). Null halves ⇒ nothing written ⇒ the id-order rule, exactly
        // as before this shipped.
        mySecretHalf: ByteArray? = null,
        peerSecretHalf: ByteArray? = null,
        peerRoleRuleV2: Boolean = false,
        // The GROUP-text inbox pair — the third pairing inbox. Appended LAST, and
        // all four nullable, so (a) every existing caller keeps compiling and (b) a
        // pairing with a peer that announced no group inbox, or on a build whose UI
        // has not been wired yet, simply writes no `*-grp` row — which routes group
        // text down the text inbox exactly as before. Both-or-neither per side.
        peerGrpInboxId: String? = null,
        peerGrpWriteCap: String? = null,
        myGrpInboxId: String? = null,
        myGrpReadCap: String? = null,
    ) {
        val now = currentTimeMillis()
        val oneYear = VaultSeedDefaults.INBOX_LIFETIME_MS

        // The contact row + its up-to-6 inbox rows + the
        // ratchet marker are ONE atomic batch. Without this, a torn write (a later
        // insertInboxId throwing on SQLITE_FULL/IOERR/a locked keybag) left an ORPHAN
        // contact row already committed — carrying the live 32-byte sharedSecret that
        // keys every static-envelope blob to/from the peer, with nothing rolling it
        // back. withTransaction commits all-or-nothing (Android: a real SQLCipher
        // transaction; iOS: the putStringsSync write-ahead journal via the bridge),
        // so an aborted add leaves NO partial row bearing a live pairing secret. The
        // sibling referral path (ReferralManager) already wraps its equivalent writes.
        vault.withTransaction {
            // `inbox_ids` is keyed by inboxId with replace-on-conflict, so a
            // peer-supplied id that already exists would SILENTLY overwrite that row —
            // reassigning it to this brand-new contact, flipping its direction and
            // destroying the stored capability. Nothing throws today; this is the gate.
            // Checked INSIDE the transaction so the check and the writes it guards
            // commit together (the control poller can apply an inbox announce
            // concurrently and holds no lock of ours). A rejection writes NOTHING: it is
            // the first statement, and any partial state rolls back anyway.
            // NO shape validation here — that is PairingPayload.parse's job at the
            // trust boundary; duplicating it would reject ids this API accepts by design.
            firstUnavailableInboxClaim(
                vault,
                pairingClaims(
                    contactId = contactId,
                    peerInboxId = peerInboxId, peerWriteCap = peerWriteCap,
                    peerCtlInboxId = peerCtlInboxId, peerCtlWriteCap = peerCtlWriteCap,
                    peerGrpInboxId = peerGrpInboxId, peerGrpWriteCap = peerGrpWriteCap,
                    myInboxId = myInboxId, myCtlInboxId = myCtlInboxId,
                    myGrpInboxId = myGrpInboxId, myGrpReadCap = myGrpReadCap,
                ),
            )?.let { throw InboxInUseException() }
            vault.insertContact(
                ContactRecord(
                    contactId = contactId,
                    sharedSecret = sharedSecret,
                    trustLevel = VaultSeedDefaults.DEFAULT_TRUST_LEVEL,
                    alias = alias,
                    aliasLastRotated = now,
                    mnemonic = mnemonic,
                )
            )
            // Peer's outbound inbox — where we SEND (their inbox + their writeCap).
            // Skipped for a secret-only scan; the peer's inbox arrives later in-band.
            if (peerInboxId != null && peerWriteCap != null) {
                vault.insertInboxId(
                    InboxIdRecord(
                        inboxId = peerInboxId, contactId = contactId,
                        createdAt = now, expiresAt = now + oneYear,
                        direction = "outbound", cap = peerWriteCap,
                    )
                )
            }
            // Peer's CONTROL outbound inbox (v7) — our invites/announces to them.
            if (peerCtlInboxId != null && peerCtlWriteCap != null) {
                vault.insertInboxId(
                    InboxIdRecord(
                        inboxId = peerCtlInboxId, contactId = contactId,
                        createdAt = now, expiresAt = now + oneYear,
                        direction = MessageManager.DIR_OUTBOUND_CTL, cap = peerCtlWriteCap,
                    )
                )
            }
            // Our inbound inbox — where we POLL (our inbox + our readCap).
            vault.insertInboxId(
                InboxIdRecord(
                    inboxId = myInboxId, contactId = contactId,
                    createdAt = now, expiresAt = now + oneYear,
                    direction = "inbound", cap = myReadCap,
                )
            )
            // Our CONTROL inbound inbox — drained by the background poller.
            vault.insertInboxId(
                InboxIdRecord(
                    inboxId = myCtlInboxId, contactId = contactId,
                    createdAt = now, expiresAt = now + oneYear,
                    direction = MessageManager.DIR_INBOUND_CTL, cap = myCtlReadCap,
                )
            )
            // Peer's GROUP outbound inbox — our group texts to them.
            if (peerGrpInboxId != null && peerGrpWriteCap != null) {
                vault.insertInboxId(
                    InboxIdRecord(
                        inboxId = peerGrpInboxId, contactId = contactId,
                        createdAt = now, expiresAt = now + oneYear,
                        direction = MessageManager.DIR_OUTBOUND_GRP, cap = peerGrpWriteCap,
                    )
                )
            }
            // Our GROUP inbound inbox — where THEIR group texts land, so a `/peek`
            // on our 1:1 text inbox counts only 1:1 texts.
            if (myGrpInboxId != null && myGrpReadCap != null) {
                vault.insertInboxId(
                    InboxIdRecord(
                        inboxId = myGrpInboxId, contactId = contactId,
                        createdAt = now, expiresAt = now + oneYear,
                        direction = MessageManager.DIR_INBOUND_GRP, cap = myGrpReadCap,
                    )
                )
            }
            // Mark this fresh pairing ratchet-capable (text-channel forward secrecy);
            // SEND activation flips later once both inboxes exist + a first inbound.
            MessageManager.markRatchetCapable(vault, contactId)
            // The ratchet ROLE inputs, in the SAME transaction as the
            // contact they belong to — a half-written pairing must never leave a role
            // bit over a contact that does not exist, nor a contact whose role bit was
            // rolled back (it would then silently use the id-order rule while the peer
            // uses the secret order: the exact collision this closes).
            if (mySecretHalf != null && peerSecretHalf != null) {
                MessageManager.recordRatchetRoleInputs(
                    vault, contactId, mySecretHalf, peerSecretHalf, peerRoleRuleV2,
                )
            }
        }
    }

    /**
     * The exact set of `inbox_ids` rows [savePairedContact] is about to write.
     *
     * The `!= null` gates MIRROR the write conditions one-for-one (peer rows are
     * both-or-neither and absent from a secret-only scan), so the claim set can
     * never be NARROWER than the write set — a claim that is missed is a row that
     * overwrites unguarded. Keep this in lock-step with the inserts above.
     */
    private fun pairingClaims(
        contactId: String,
        peerInboxId: String?,
        peerWriteCap: String?,
        peerCtlInboxId: String?,
        peerCtlWriteCap: String?,
        peerGrpInboxId: String?,
        peerGrpWriteCap: String?,
        myInboxId: String,
        myCtlInboxId: String,
        myGrpInboxId: String?,
        myGrpReadCap: String?,
    ): List<InboxClaim> = buildList {
        if (peerInboxId != null && peerWriteCap != null) {
            add(InboxClaim(peerInboxId, contactId, "outbound"))
        }
        if (peerCtlInboxId != null && peerCtlWriteCap != null) {
            add(InboxClaim(peerCtlInboxId, contactId, MessageManager.DIR_OUTBOUND_CTL))
        }
        if (peerGrpInboxId != null && peerGrpWriteCap != null) {
            add(InboxClaim(peerGrpInboxId, contactId, MessageManager.DIR_OUTBOUND_GRP))
        }
        add(InboxClaim(myInboxId, contactId, "inbound"))
        add(InboxClaim(myCtlInboxId, contactId, MessageManager.DIR_INBOUND_CTL))
        if (myGrpInboxId != null && myGrpReadCap != null) {
            add(InboxClaim(myGrpInboxId, contactId, MessageManager.DIR_INBOUND_GRP))
        }
    }
}
